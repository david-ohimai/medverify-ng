/**
 * One evaluation page for the document and the slides: docs/eval-results.md,
 * built from the latest runs of the three evals plus live review-queue
 * agreement (how often a human reviewer agreed with the system).
 *
 *   npm run eval -- --fresh && npm run eval:rag && npm run eval:agent && npm run eval:report
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { prisma } from "../src/lib/prisma.js";
import { redis } from "../src/lib/redis.js";
import { reviewService } from "../src/services/review/review.service.js";

const RESULTS = fileURLToPath(new URL("../eval/results/", import.meta.url));
const OUT = fileURLToPath(new URL("../../docs/eval-results.md", import.meta.url));

function load<T>(file: string): T | null {
  return existsSync(`${RESULTS}${file}`) ? (JSON.parse(readFileSync(`${RESULTS}${file}`, "utf8")) as T) : null;
}

interface PhotoRun {
  summary: { ranAt: string; cases: number; passed: number; verdictAccuracy: string; fakesPassedAsGenuine: string; falseAlarms: string; fieldAccuracy: string; medianLatencyMs: number };
  results: Array<{ id: string; passed: boolean; verdict: string | null; failure: string | null; riskScore: number | null; ms: number }>;
}
interface RagRun {
  summary: { ranAt: string; hitAt1: string; recallAt3: string; mrr: number; offTopicRejected: string };
}
interface AgentRun {
  ranAt: string;
  results: Array<{ id: string; passed: boolean; called: string[]; citations: number; ms: number }>;
}

async function main(): Promise<void> {
  const photo = load<PhotoRun>("latest.json");
  const rag = load<RagRun>("rag-latest.json");
  const agent = load<AgentRun>("agent-latest.json");
  const reviews = await reviewService.stats();

  const lines: string[] = [
    "# MedVerify NG — evaluation results",
    "",
    "> Generated by `npm run eval:report` from the latest eval runs. The photo cases are **drawn, fictional demo packs** (X9- numbers): they prove the pipeline end to end, not real-world accuracy — real pack photos are added to `server/eval/` as they are taken.",
    "",
    "| Area | Headline | Run |",
    "|---|---|---|",
    `| Photo pipeline (read label → registry → compare → score) | ${photo ? `**${photo.summary.passed}/${photo.summary.cases}** passed · **fakes passed as genuine: ${photo.summary.fakesPassedAsGenuine}** · false alarms ${photo.summary.falseAlarms} · fields read ${photo.summary.fieldAccuracy}` : "not run"} | ${photo?.summary.ranAt.slice(0, 10) ?? "—"} |`,
    `| Retrieval over official WHO/NAFDAC documents | ${rag ? `hit@1 **${rag.summary.hitAt1}** · recall@3 **${rag.summary.recallAt3}** · MRR **${rag.summary.mrr}** · off-topic rejected ${rag.summary.offTopicRejected}` : "not run"} | ${rag?.summary.ranAt.slice(0, 10) ?? "—"} |`,
    `| Assistant (tool choice, citations, exact details) | ${agent ? `**${agent.results.filter((r) => r.passed).length}/${agent.results.length}** passed` : "not run"} | ${agent?.ranAt.slice(0, 10) ?? "—"} |`,
    `| Human review agreement (live) | ${reviews.decided.total - reviews.decided.inconclusive >= 5 ? `reviewers agreed with the system **${reviews.decided.agreementRate}%** of ${reviews.decided.total - reviews.decided.inconclusive} conclusive decisions · median ${reviews.decided.medianMinutesToDecision} min to decide` : `too few decisions yet (${reviews.decided.total}) — fills in as reviewers work the queue`} | live |`,
    "",
  ];

  if (photo) {
    lines.push(
      "## Photo pipeline",
      "",
      `Median latency ${Math.round(photo.summary.medianLatencyMs / 1000)} s per scan on the free tier (two vision calls; includes rate-limit waits and fallbacks to OpenRouter).`,
      "",
      "| Case | Result | Outcome | Score | s |",
      "|---|---|---|---|---|",
      ...photo.results.map((r) => `| ${r.id} | ${r.passed ? "✓" : "✗"} | ${r.verdict ?? r.failure} | ${r.riskScore ?? "—"} | ${Math.round(r.ms / 1000)} |`),
      ""
    );
  }
  if (agent) {
    lines.push(
      "## Assistant",
      "",
      "| Case | Result | Tools called | Citations |",
      "|---|---|---|---|",
      ...agent.results.map((r) => `| ${r.id} | ${r.passed ? "✓" : "✗"} | ${r.called.join(", ") || "—"} | ${r.citations} |`),
      ""
    );
  }
  lines.push(
    "## How to reproduce",
    "",
    "```bash",
    "cd server",
    "npm run seed && npm run kb:ingest && npm run simulate",
    "npm run eval -- --fresh   # photo pipeline, real AI calls",
    "npm run eval:rag          # retrieval",
    "npm run eval:agent        # assistant",
    "npm run eval:report       # this page",
    "```",
    ""
  );

  writeFileSync(OUT, lines.join("\n"));
  console.log("Wrote docs/eval-results.md");
}

main()
  .catch((err: unknown) => {
    console.error("Eval report failed:", err instanceof Error ? err.message : err);
    process.exitCode = 1;
  })
  .finally(async () => {
    await Promise.allSettled([prisma.$disconnect(), redis.quit()]);
  });
